"""Оценка сложности вопроса для автоматического выбора режима ответа.

Сначала работает быстрая эвристика, затем (если доступна модель) — короткий
классификатор. Эвристика остаётся запасным вариантом: она не тратит токены и
работает в демо-режиме и на локальной модели.
"""

from __future__ import annotations

import re
from typing import Optional, Tuple

FAST_HINTS = (
    "привет",
    "здравствуйте",
    "добрый день",
    "спасибо",
    "пока",
    "кто вы",
    "что вы умеете",
    "как дела",
)

THINKING_HINTS = (
    "сравн",
    "проанализ",
    "почему",
    "зачем",
    "насколько",
    "отлича",
    "разниц",
    "лучше",
    "хуже",
    "топ",
    "рейтинг",
    "самы",
    "список",
    "таблиц",
    "динамик",
    "прирост",
    "тренд",
    "зависит",
    "влияет",
    "подробно",
    "объясни",
    "что входит",
    "какие условия",
    "сколько всего",
    "кто из",
    "и ещё",
    "а также",
)

MODE_PROMPT = (
    "Ты классификатор вопроса для ассистента компании. Ответь одним словом: "
    "FAST — простой факт или приветствие, можно ответить сразу; "
    "THINKING — нужен разбор, сравнение или подсчёт, но данных в вопросе достаточно; "
    "CLARIFY — запрос описывает цель или потребность без конкретного объекта и параметров, "
    "либо просит подобрать, выбрать, записаться или выполнить действие, но не указан "
    "параметр, который знает только клиент, либо запрос допускает несколько равнозначных "
    "путей. Вопросы о процессе, форматах, условиях, составе и стоимости названного "
    "объекта — не CLARIFY. "
    "Не выбирай CLARIFY, если вопрос про конкретный названный объект («расскажи о …», "
    "«что такое …», «сколько стоит …») или если можно ответить/сказать об отсутствии данных. "
    "Без пояснений."
)


def _words(question: str) -> int:
    return len(re.findall(r"[\w-]+", question, re.UNICODE))


def heuristic_mode(question: str) -> Tuple[str, str]:
    """Возвращает (режим, короткое объяснение) без обращения к модели."""
    text = " ".join((question or "").split())
    if not text:
        return "fast", "пустой вопрос"
    lowered = text.lower()
    words = _words(text)

    if words <= 4 and any(hint in lowered for hint in FAST_HINTS):
        return "fast", "короткое приветствие"

    for hint in THINKING_HINTS:
        if hint in lowered:
            return "thinking", "нужен разбор или сравнение"

    if text.count("?") >= 2:
        return "thinking", "несколько вопросов сразу"
    if words >= 24:
        return "thinking", "длинный составной вопрос"
    if words <= 8:
        return "fast", "короткий фактовый вопрос"
    return "fast", "один вопрос без анализа"


def parse_mode(text: str) -> Optional[str]:
    """Разбирает ответ классификатора."""
    upper = (text or "").upper()
    if "THINKING" in upper or "МЫШЛ" in upper:
        return "thinking"
    if "CLARIFY" in upper or "УТОЧН" in upper:
        return "clarify"
    if "FAST" in upper or "БЫСТР" in upper:
        return "fast"
    return None
